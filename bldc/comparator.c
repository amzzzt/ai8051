#include "zf_driver_gpio.h"
#include "comparator.h"
#include "motor_control.h"

//-------------------------------------------------------------------------------------------------------------------
//  比较器模块，负责反电动势过零检测
//
//  无感无刷电机没有霍尔传感器，只能靠反电动势判断转子位置。六步换相任意时刻都是
//  两相导通、一相悬空，悬空相的端电压就等于该相的反电动势。把这个电压和三相的
//  虚拟中性点比较，电平翻转的那一刻就是该相反电动势过零点。
//
//  硬件连接：
//      P46 = A 相端电压
//      P50 = B 相端电压
//      P51 = C 相端电压
//      P44 = 虚拟中性点（三相同阻值电阻星形连接的中点）
//      P41 = 比较器输出，接到比较器中断
//
//  CMPEXCFG 寄存器决定拿哪一相和中性点比较，也就是 comparator.h 里的
//  CMP_SELECT_A / CMP_SELECT_B / CMP_SELECT_C 三个宏，由六步换相函数调用。
//
//  过零之后并不立刻换相，还要再等 BLDC_MOTOR_ANGLE 度（默认 10 度）才换，
//  这段延时由 motor_control.c 的比较器中断用定时器 0 完成。
//-------------------------------------------------------------------------------------------------------------------


// 虚拟中性点输入引脚
#define COMPARATOR_MID_PIN  IO_P44

// 三相端电压输入引脚
#define COMPARATOR_A_PIN    IO_P46
#define COMPARATOR_B_PIN    IO_P50
#define COMPARATOR_C_PIN    IO_P51


// 比较器输出极性取反位宏。
// 左移 6 位对应 CMPCR2 的 bit6 位置，(0 << 6) 即不取反。
// 这个宏在当前代码中未被使用，保留而已。
#define CMP_DC_LAG    (0 << 6)

//-------------------------------------------------------------------------------------------------------------------
//  @brief      配置比较器上升沿触发中断
//  @param      void
//  @return     void
//  @since      v1.0
//  Sample usage:
//-------------------------------------------------------------------------------------------------------------------
void comparator_rising(void)
{
    // 配置上升沿
    // CMPCR1 写成 0xA2，各比特位含义：
    //   CMPEN = 1   比较器使能
    //   CMPIF = 0   清比较器中断请求标志
    //   PIE   = 1   上升沿中断使能
    //   NIE   = 0   下降沿中断关闭
    //   CMPOE = 1   比较结果输出到 CMPO_S 选定的引脚
    CMPCR1 = 0xA0 | 0x02;
}

//-------------------------------------------------------------------------------------------------------------------
//  @brief      配置比较器下降沿触发中断
//  @param      void
//  @return     void
//  @since      v1.0
//  Sample usage:
//-------------------------------------------------------------------------------------------------------------------
void comparator_falling(void)
{
    //下降沿
    // CMPCR1 写成 0x92，与上面相比把使能的中断沿换成了 NIE：
    //   CMPEN = 1   比较器使能
    //   CMPIF = 0   清比较器中断请求标志
    //   PIE   = 0   上升沿中断关闭
    //   NIE   = 1   下降沿中断使能
    //   CMPOE = 1   比较结果输出到引脚
    CMPCR1 = 0x90 | 0x02;
}

//-------------------------------------------------------------------------------------------------------------------
//  @brief      读取比较结果
//  @param      void
//  @return     void
//  @since      v1.0
//  Sample usage:
//-------------------------------------------------------------------------------------------------------------------
uint8 comparator_result_get(void)
{
    // CMPCR1 的 bit0 就是比较器当前输出电平
    return (CMPCR1&0x01);
}

//-------------------------------------------------------------------------------------------------------------------
//  @brief      关闭比较器中断
//  @param      void
//  @return     void
//  @since      v1.0
//  Sample usage:
//-------------------------------------------------------------------------------------------------------------------
void comparator_close_isr(void)
{
    // CMPCR1 写成 0x82：CMPEN 仍然为 1，比较器本体继续工作，
    // 但 PIE 和 NIE 都清零，上升沿和下降沿中断都不再触发。
    // 换相之后到消磁结束之前要调用它，避免换相瞬间的电压抖动被当成过零点。
    CMPCR1 = 0x80 | 0x02;
}

//-------------------------------------------------------------------------------------------------------------------
//  @brief      打开比较器中断
//  @param      void
//  @return     void
//  @since      v1.0
//  Sample usage:
//-------------------------------------------------------------------------------------------------------------------
void comparator_open_isr(void)
{
	// 先清比较器中断标志位，否则会立刻再进一次中断
	CMPCR1 &= ~0x40;

	// 打开比较器中断
	// 该侦测上升沿还是下降沿，取决于当前监测的是哪一相。
	// 六步换相里 step 为奇数是监测相反电动势下降的相位，用上升沿；
	// step 为偶数则相反，用下降沿。
	if(motor.step % 2)
	{
		comparator_rising();
	}
	else
	{
		comparator_falling();
	}
}

//-------------------------------------------------------------------------------------------------------------------
//  @brief      比较器初始化
//  @param      void
//  @return     void
//  @since      v1.0
//  Sample usage:
//-------------------------------------------------------------------------------------------------------------------
void comparator_init(void)
{
    // P45 是比较器输出的备用引脚，这里先配成高阻输入。
    // 下面 CMPO_S = 1 会把比较器输出改到 P41，所以 P45 实际不输出。
    gpio_init(IO_P45, GPI, 0, GPI_IMPEDANCE);

    gpio_init(COMPARATOR_MID_PIN, GPI, 0, GPI_IMPEDANCE); // 中性点
    gpio_init(COMPARATOR_A_PIN  , GPI, 0, GPI_IMPEDANCE); // A
	gpio_init(COMPARATOR_B_PIN  , GPI, 0, GPI_IMPEDANCE); // B
	gpio_init(COMPARATOR_C_PIN  , GPI, 0, GPI_IMPEDANCE); // C

    // CMPCR1 = 0x8E：比较器使能，中断标志清零，两个沿的中断都先关掉，
    // 同时打开比较结果输出（CMPOE），等真正进入闭环时再由 comparator_open_isr 决定沿。
    CMPCR1 = 0x8C | 1 << 1;	// 1000 1100

    // CMPCR2 的 bit6 置 1，低 6 位 LCDTY 设为 63。
    // 按原始注释：63 是延时滤波值，同时关闭 0.1uf 滤波电容相关的功能。
    CMPCR2 = 63 | 1 << 6;	// 63延时滤波，关闭0.1uf滤波电容功能

    // 比较器输出选择位 0->P45 1->P41
    CMPO_S = 1;             // 比较器输出选择位 0->P45 1->P41

}
