#ifndef _bldc_config_h_
#define _bldc_config_h_

//-------------------------------------------------------------------------------------------------------------------
//  本文件集中了电调所有可调参数。调参只需要改这里，不需要动任何逻辑代码。
//
//  【调参顺序】
//    1. BLDC_POLES         电机极对数，最先确认。填错会导致换相时序全乱。
//    2. BLDC_PWM_ARR_MAX   PWM 周期，必须与系统主频匹配。
//    3. BLDC_PWM_DEADTIME  死区，按驱动管开关速度调，绝不能为 0。
//    4. BLDC_MIN/MAX_DUTY  启动占空比，决定能不能启动、启动电流多大。
//    5. 其余参数按实际现象微调。
//
//  【单位说明】本文件里多数时间量以定时器计数为单位，换算关系写在各自注释里。
//-------------------------------------------------------------------------------------------------------------------


//-------------------------------------------------------------------------------------------------------------------
//  PWM 相关
//-------------------------------------------------------------------------------------------------------------------

// 40000000 / 43333 = 923.08
// 40000000 为系统频率40Mhz
// 43333为43.333Khz
//
// 计算依据：本芯片 PWMA 计数时钟 = 系统主频 / (PWMA_PSCRL + 1)，本工程预分频为 0，
// 所以计数时钟就是主频。向上计数模式下 PWM 周期 = (ARR + 1) / 计数时钟，即
// PWM 频率 = 主频 / (ARR + 1) = 40000000 / 924 = 43290Hz，与 43.333kHz 基本吻合。
//
// 注意：改了系统主频（main.c 里的 clock_init）之后此值必须重算，否则 PWM 频率会跟着跑偏。
//       v2.0.2 把 PWM 频率从 48kHz 降到 43.333kHz，是为了避开 20kHz 电磁干扰源的谐波。
#define BLDC_PWM_ARR_MAX                (923)     		// PWM的最大占空比，需要自行根据PWM初始化去计算

#define BLDC_MAX_DUTY                   (10)      	    // 启动最大占空比，单位百分之一
														// 即最大 10% 占空比，用于限制启动瞬间的电流，防止烧管或触发过流保护。

#define BLDC_MIN_DUTY                   (5)      		// 启动最小占空比，单位百分之一
														// 即最小 5% 占空比，太小电机得不到足够转矩启不动，太大会启动过猛。
														// 闭环运行时占空比的下限也是这个值。

#define BLDC_PWM_DEADTIME				(5)	            // PWM输出死区
														// 写入 PWMA_DTR，防止同一桥臂上下管直通。
														// 绝对不能设为 0，直通等于电源短路，必炸功率管。
														// 数值按驱动管的开通/关断时间确定，宁大勿小。

//-------------------------------------------------------------------------------------------------------------------
//  电池保护
//-------------------------------------------------------------------------------------------------------------------

#define BLDC_MIN_BATTERY                (8000)   		// 最小电压，单位mv，当检测到电压低于此值电机停转
														// 且要求连续 2 秒低于该值才真正保护（见 battery.c），避免瞬时压降误触发。

//-------------------------------------------------------------------------------------------------------------------
//  堵转保护
//-------------------------------------------------------------------------------------------------------------------

#define BLDC_COMMUTATION_FAILED_MAX     (200)     		// 换相错误最大次数 大于这个次数后认为电机堵转
														// 换相错误判定见 motor_control.c 的 TM0_Isr：
														// 本次换相耗时不在"整圈时间的 30/360 至 90/360"区间内就记一次错误。
														// 调小则保护更灵敏但易误停，调大则不易误停但堵转后保护更慢。
														// 正常换相会递减此计数，所以偶发错误不会累积。

#define BLDC_START_DELAY                (10000)   		// 当遇到堵转后电机停止时间，之后电机会再次尝试启动（单位0.05ms）
														// 10000 乘 50us = 500ms 的停机等待，给电机足够时间停稳再重启。

//-------------------------------------------------------------------------------------------------------------------
//  启动与闭环切换
//-------------------------------------------------------------------------------------------------------------------

#define BLDC_CLOSE_LOOP_WAIT        	(200 )          // 闭环等待换向次数
														// 进入闭环后再等这么多次换相，才开始执行换相错误判定和加减速斜坡。
														// 目的是等转速稳定，否则刚闭环时的抖动会被误判成换相错误。

#define BLDC_OPEN_LOOP_WAIT        		(200 )          // 闭环等待换向次数
														// 名字有歧义，实际含义是"开环阶段要完成多少次换相才切闭环"。
														// 本电调最关键的参数之一：
														//   调小则切闭环太早，转速还不够、反电动势太弱，检测不到过零导致失步；
														//   调大则启动慢、开环阶段发热大、耗电。
														// 建议以能稳定启动的最小值为准。

//-------------------------------------------------------------------------------------------------------------------
//  速度控制
//-------------------------------------------------------------------------------------------------------------------

#define BLDC_SPEED_INCREMENTAL      	(2)             // 加减速响应 1-20，可修改这个提高加速响应，
														// 设置20响应速度最慢，设置1响应速度最快。
														// 响应速度越快，越容易出现换相错误，所以建议从20开始，一点一点减小。
														// 实现方式见 pit_timer.c：用 pit_count 对该值取模作为门控，
														// 决定这个 50us 周期要不要调整一次占空比，所以数值越大斜坡越慢。

//-------------------------------------------------------------------------------------------------------------------
//  电机本体参数
//-------------------------------------------------------------------------------------------------------------------

#define BLDC_POLES                  	(7)             // 电机极对数
														// 必须与实际电机一致，这是最容易搞错、后果最严重的参数。
														// 极对数不等于磁极数，7 对极对应 14 个磁极。
														// 填错的后果：换相时序与实际转子位置完全对不上，轻则启动不了、
														// 剧烈抖动，重则持续堵转把线圈烧掉。
														// 本参数用于 sine_control.c 的正弦强拉步进延时：sine_delay = 420 / BLDC_POLES。

//-------------------------------------------------------------------------------------------------------------------
//  上电提示音
//-------------------------------------------------------------------------------------------------------------------

#define BLDC_BEEP_ENABLE                (1 )      		// 1:使能上电电机鸣叫功能 0：禁用
														// 上电鸣叫即初始化成功的自检提示，听到声音说明时钟、PWM、驱动都正常。

#define BLDC_BEEP_VOLUME                (60)    	 	// 电机鸣叫声音大小 0-100
														// 直接作为鸣叫时的 PWM 占空比，代码里有 100 的上限保护。
														// 原理是用电机线圈当喇叭，三相轮流导通发出 523/587/659/698/783Hz 的音阶。

//-------------------------------------------------------------------------------------------------------------------
//  换相时序
//-------------------------------------------------------------------------------------------------------------------

#define BLDC_MOTOR_ANGLE				(10)			// 马达进角，进入比较器中断后，延时多少度进行换相
														// 范围0-30度
														// 理论上过零点之后转子再转 30 度电角度换相最优，但实际因绕组电感
														// 导致电流滞后，需要提前换相（即进角），否则高速时转矩下降、效率变差。
														// 实现：比较器中断里把 T0 装载为"整圈时间 乘 BLDC_MOTOR_ANGLE 除 360"，
														// 延时到期后触发 TM0_Isr 执行换相。
														// 调大则高速性能更好，但过大可能在低速时提前换相导致失步。

//-------------------------------------------------------------------------------------------------------------------
//  启动方式
//-------------------------------------------------------------------------------------------------------------------

#define BLDC_USE_SINE_START             (1)   			// 使用正弦启动
														// 1 用 sine_control.c 的正弦强拉启动，旋转磁场拖动转子，平顺且成功率高；
														// 0 用纯开环延时启动，按固定时间间隔硬拖，实现简单但易失步。
														// 生效位置：pit_timer.c 的 MOTOR_START 状态里用 #if 分支。

#define BLDC_USR_COMPLEMENTARY          (1)             // 1:使能互补输出 0：禁用
														// 开启后 PWMA_ENO 会同时使能上桥和下桥的互补通道，由硬件自动插死区，
														// 开关损耗略高但波形更好。
														// 生效位置：pwm_out.c 的六个换相函数里用 #if 选择 ENO 取值。

#endif
