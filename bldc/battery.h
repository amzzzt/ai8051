#ifndef _battery_h
#define _battery_h

#include "zf_common_typedef.h"

//-------------------------------------------------------------------------------------------------------------------
//  电池电压检测模块
//
//  用 ADC 加 DMA 的方式自动采样电池分压后的电压，换算成实际电池电压，
//  用于低压保护：连续 2 秒低于 BLDC_MIN_BATTERY 就禁止电机运行。
//
//  采样引脚 P15，DMA 数据固定存放在地址 0x800。
//  采样由 TM1_Isr 每 50us 调用一次 battery_voltage_get() 来驱动。
//
//  实现文件：battery.c
//-------------------------------------------------------------------------------------------------------------------


// 电池低压标志。当前代码中未见赋值点，实际使用的是 battery_voltage_get() 的返回值。
extern uint8  battery_low_voltage;

// 换算后的电池电压，单位毫伏。
// 计算方式：ADC 值乘 3300 除 256 得到引脚电压，再乘 6（分压比 120k 比 20k）得到电池电压。
extern uint16 battery_voltage;

// ADC 原始寄存器值。当前代码中它只是 battery_voltage_get() 内部的局部变量，
// 这里的全局声明未见定义和使用，保留而已。
extern uint16 adc_reg_value;

// 读取并换算电池电压，同时启动下一次 DMA 转换。
// 返回值：0 表示电压正常，1 表示电压过低需要保护。
// 判据是连续 2 秒低于阈值才返回 1，避免瞬时压降误触发。
uint8 battery_voltage_get(void);

// 电池检测初始化：配置 P15 为高阻输入，使能 ADC，配置 DMA 自动搬运，
// 并立即采集一次电压。
void battery_init(void);

#endif
