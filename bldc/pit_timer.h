#ifndef _pit_timer_h_
#define _pit_timer_h_


#include "zf_common_typedef.h"

//-------------------------------------------------------------------------------------------------------------------
//  周期定时器模块，是整个电调的主控制循环
//
//  pit_timer_init() 把 TIM1 配成 50us 一次的中断，即 20kHz。
//  中断服务函数 TM1_Isr（在 pit_timer.c 中）每次做三件事：
//    1. 累计 pit_count，供 LED 闪烁和加减速斜坡做时间基准
//    2. 调用 battery_voltage_get() 检查电池电压
//    3. 更新 motor.run_flag 并调用 led_control() 和 pit_motor_control()
//
//  pit_motor_control() 就是电机状态机的主体，电机的所有行为都在这里推进。
//
//  实现文件：pit_timer.c
//-------------------------------------------------------------------------------------------------------------------


// 周期定时器初始化：把 TIM1 配成 50us 中断一次，并让电机进入空闲状态。
// 必须在所有外设初始化完成之后调用，因为一开中断状态机就开始跑了。
void pit_timer_init(void);

// LED 初始化：把 P36（RUN）和 P37（ERR）配成推挽输出，并熄灯。
// LED 为低电平点亮，所以写 1 是熄灭。
void led_init(void);

// 声明保留。实际代码里 gpio_state 是 pit_motor_control() 内部的静态局部变量，
// 并没有在文件作用域定义，所以这个 extern 声明目前没有对应的实体。
extern uint8 gpio_state;

#endif
