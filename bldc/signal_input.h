#ifndef _signal_input_h
#define _signal_input_h


#include "zf_common_typedef.h"

//-------------------------------------------------------------------------------------------------------------------
//  油门信号输入模块
//
//  从 P21 引脚捕获外部 RC 油门信号，也就是航模接收机输出的标准 PWM：
//  周期 20ms 左右，高电平宽度 1ms 至 2ms 表示油门 0 至 100%。
//
//  使用 PWMB 的两个输入捕获通道分别测周期和高电平宽度，中断号为 27，
//  中断服务函数是 signal_input.c 的 pwmb_isr()。
//
//  实现文件：signal_input.c
//-------------------------------------------------------------------------------------------------------------------


//-------------------------------------------------------------------------------------------------------------------
//  油门信号解析结果
//
//  由输入捕获中断填写，主控制循环读取。
//  注意这些字段会被中断随时改写，读取时如果需要一致性，要先关中断拷贝。
//-------------------------------------------------------------------------------------------------------------------
typedef struct
{
    uint16 frequency;   // 信号频率
                        // 由周期换算得到：system_clock / (PSCRL+1) / period。
                        // 只在 30Hz 至 400Hz 范围内才认为是有效信号。

    uint16 period;      // 信号周期
                        // 单位是捕获计数器的计数值。计数时基为 1us，所以数值等同于微秒。

    uint16 high_value;  // 信号高电平计数值
                        // 同样以 1us 为时基，所以数值等同于高电平的微秒数。

    uint16 high_time;   // 信号高电平时间 us
                        // 由 high_value 赋值而来，并做了 2000 的上限钳位。

    uint16 throttle;    // 输出油门大小
                        // 归一化到 0 至 1000 的油门值，由高电平时间换算：
                        // throttle = high_time - 1000，小于 50 时直接归零，避免死区抖动。
                        // 最终 motor.duty 由它乘 BLDC_PWM_ARR_MAX 再除 1000 得到。
}pwmin_struct;


// 全局油门解析结果实例，由 pwmb_isr 填写。
extern pwmin_struct pwmin;

// 油门输入捕获初始化：配置 P21、P23 为高阻输入，设置 PWMB 双通道输入捕获、
// 1us 计数时基、上升沿复位模式、使能三个中断源。
void pwm_input_init(void);

#endif
