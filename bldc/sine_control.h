#ifndef _sine_control_h
#define _sine_control_h
#include "zf_common_typedef.h"

//-------------------------------------------------------------------------------------------------------------------
//  正弦启动模块
//
//  作用：电机静止时反电动势为零，比较器检测不到过零，无法闭环。
//        所以启动阶段先用三相正弦调制产生一个旋转磁场，把转子强行拖动起来，
//        等转速上来之后再切换到六步换相的无感闭环。
//
//  原理：用一张 360 点正弦表，三相各取相差 120 度的相位点，每拍更新一次 PWM 比较值，
//        合成出旋转的磁场矢量。电机极对数越小，每步对应的机械角度越大。
//
//  本文件没有版权头，是逐飞原始文件本来就如此。
//  实现文件：sine_control.c
//-------------------------------------------------------------------------------------------------------------------


// 三相在正弦表中的当前相位索引，取值 0 至 359，代表电角度。
// 三者初始相差 120 度（0、119、239），由 sine_init() 设置。
// sine_start() 每调用一次就把三个位置都减一，产生反转的旋转磁场。
extern int16 motor_a_position;
extern int16 motor_b_position;
extern int16 motor_c_position;


// 正弦启动初始化：把三相相位设为相差 120 度，开启所有 PWM 通道和比较输出。
// 注意运行时的相位是"每拍减一"，所以顺时针拖动转子。
void sine_init(void);

// 正弦强拉一步：三相相位各减一，按正弦表把对应幅值乘上占空比后写入三路比较寄存器。
// 参数 duty 是本次输出的PWM幅值，对应正弦表的峰值 1024 做等比缩放。
// 由 pit_timer.c 的 MOTOR_START 状态循环调用，直到 motor_a_position 回到 0，
// 也就是相位转过完整一圈。
void sine_start(uint16 duty);

#endif
