#ifndef _conparator_h_
#define _conparator_h_

#include "zf_common_typedef.h"

//-------------------------------------------------------------------------------------------------------------------
//  比较器模块，负责反电动势过零检测
//
//  无感 BLDC 的核心原理：三相全桥任意时刻只有两相导通，第三相悬空。
//  悬空相的反电动势会随转子位置变化穿过中点电压，这个过零事件就是转子位置信号。
//  本模块用芯片内置比较器比较悬空相电压与虚拟中性点电压，过零时产生中断。
//
//  硬件连接（见 comparator.c）：
//      P44 虚拟中性点    P46 A相    P50 B相    P51 C相    P41 比较器输出
//
//  实现文件：comparator.c
//-------------------------------------------------------------------------------------------------------------------


//-------------------------------------------------------------------------------------------------------------------
//  @brief      比较器选择A通道为输入
//  @param      void
//  @return     void
//  @since      v1.0
//  Sample usage:
//  说明：CMPEXCFG 是比较器扩展配置寄存器，低 2 位选择负端输入通道。
//        切换监测相必须与当前换相步序匹配，哪一相悬空就监测哪一相。
//        调用点：pwm_out.c 的 pwm_b_cn_output 和 pwm_c_bn_output。
//-------------------------------------------------------------------------------------------------------------------
#define CMP_SELECT_A    (CMPEXCFG = 0x00)


//-------------------------------------------------------------------------------------------------------------------
//  @brief      比较器选择B通道为输入
//  @param      void
//  @return     void
//  @since      v1.0
//  Sample usage:
//  调用点：pwm_out.c 的 pwm_a_cn_output 和 pwm_c_an_output。
//-------------------------------------------------------------------------------------------------------------------
#define CMP_SELECT_B    (CMPEXCFG = 0x01)

//-------------------------------------------------------------------------------------------------------------------
//  @brief      比较器选择C通道为输入
//  @param      void
//  @return     void
//  @since      v1.0
//  Sample usage:
//  调用点：pwm_out.c 的 pwm_a_bn_output 和 pwm_b_an_output。
//-------------------------------------------------------------------------------------------------------------------
#define CMP_SELECT_C    (CMPEXCFG = 0x02)


// 电机换相时间。当前代码中未见赋值点，声明保留。
extern uint16 motor_commutation_time;


//-------------------------------------------------------------------------------------------------------------------
//  对外接口
//-------------------------------------------------------------------------------------------------------------------

// 配置比较器为上升沿触发中断。
// 原理：CMPCR1 写 0xA0 | 0x02，其中 0xA0 使能比较器与中断，0x02 选择上升沿触发。
void  comparator_rising(void);

// 配置比较器为下降沿触发中断。
// 原理：CMPCR1 写 0x90 | 0x02。
void  comparator_falling(void);

// 读取比较器当前输出电平，返回 CMPCR1 的最低位。
// 用于开环阶段轮询电平跳变（见 pit_timer.c），以及闭环里的堵转检测。
uint8 comparator_result_get(void);

// 关闭比较器中断，但保留比较器本身使能。
// 换相后到下次过零前调用，避免同一段区间被重复触发。
// 原理：CMPCR1 写 0x80 | 0x02。
void  comparator_close_isr(void);

// 打开比较器中断，并自动按 motor.step 的奇偶选择上升沿还是下降沿。
// 这是无感换相能正确工作的关键：换相后悬空相电压的变化方向是交替的。
// 调用时机：换相后等待消磁延时结束时，见 motor_control.c 的 TM0_Isr。
void  comparator_open_isr(void);

// 比较器初始化：配置 P44、P45、P46、P50、P51 为高阻输入，设置数字滤波和输出引脚。
void  comparator_init(void);

#endif
