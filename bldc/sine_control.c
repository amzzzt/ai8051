//-------------------------------------------------------------------------------------------------------------------
//  @brief      正弦启动初始化
//  @param      void
//  @return     void
//  @since      v1.0
//  Sample usage:
//-------------------------------------------------------------------------------------------------------------------
void sine_init(void)
{
	// 设置相位
	// A 相从 0 度开始，B 相超前 119 度，C 相超前 239 度，三者相差约 120 度。
	motor_a_position = 0;
	motor_b_position = motor_a_position + 119;
	motor_c_position = motor_a_position + 239;

	// 打开PWM输出
	// CCER1 的 8 个使能位分别对应通道 1、2 的上下桥，CCER2 的低 4 位对应通道 3。
	// 正弦启动要三相同时出力，所以全部打开。
	PWMA_CCER1 = 0xFF;
	PWMA_CCER2 = 0x0F;

	// 使能PWM所有通道
	// ENO 的 6 个位对应六路输出，0x3F 即六路全开。
	// 这一点和六步换相不同，六步换相每步只开一到两路。
	PWMA_ENO = 0x3F;
}



//-------------------------------------------------------------------------------------------------------------------
//  @brief      正弦强拉
//  @param      void
//  @return     void
//  @since      v1.0
//  Sample usage:
//-------------------------------------------------------------------------------------------------------------------
// 每调用一次，三相相位同时减一，也就是磁场朝一个固定方向旋转一格。
// 由 pit_timer.c 的 MOTOR_START 状态在一个 do-while 循环里连续调用，
// 每次调用后等 sine_delay 个计数，直到 motor_a_position 减回 0，
// 也就是磁场整整转过一圈 360 度。此时转子已经被强行拖动起来，可以切闭环了。
//
// 参数 duty 是本次输出的 PWM 幅值，对应正弦表峰值 1024 做等比缩放。
void sine_start(uint16 duty)
{
	uint16 temp = 0;

	// 三相相位各自减一，减到负数就回绕到 359，形成 0 至 359 的循环。
	// 因为一直是减，所以磁场是反转的，对应电机的某一个固定转向。
	motor_a_position --;
	if (motor_a_position < 0)
	{
		motor_a_position = 359 ;
	}

	motor_b_position --;
	if (motor_b_position < 0)
	{
		motor_b_position = 359;
	}

	motor_c_position --;
	if (motor_c_position < 0)
	{
		motor_c_position = 359 ;
	}

//	temp = ((uint32)sine_pwm_arr[motor_a_position]  * duty) / 1024;		// 1024为sine_pwm的峰值
	// 查表取 A 相这一点的正弦幅值，乘上幅值参数后右移 10 位，
	// 等价于除以 1024，比除法快很多，在 20kHz 的循环里差别很明显。
	temp = ((uint32)sine_pwm_arr[motor_a_position] * duty) >> 10;

	// 比较值分高低字节写入，A 相用 CCR1
	PWMA_CCR1H = (temp >> 8) & 0xFF;
    PWMA_CCR1L = temp & 0xFF;

    // B 相用 CCR2
	temp = ((uint32)sine_pwm_arr[motor_b_position] * duty) >> 10;
    PWMA_CCR2H = (temp >> 8) & 0xFF;
    PWMA_CCR2L = temp & 0xFF;

    // C 相用 CCR3
	temp = ((uint32)sine_pwm_arr[motor_c_position] * duty) >> 10;
    PWMA_CCR3H = (temp >> 8) & 0xFF;
    PWMA_CCR3L = temp & 0xFF;

}
